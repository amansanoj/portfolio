(() => {
  const themeToggleBtn = document.getElementById('theme-toggle');
  const iconSun = document.getElementById('icon-sun');
  const iconMoon = document.getElementById('icon-moon');

  if (!themeToggleBtn || !iconSun || !iconMoon) return;

  /** Match icon visibility to the active theme. */
  function syncThemeIcons() {
    const isDark = document.documentElement.classList.contains('dark');
    iconSun.style.display = isDark ? 'flex' : 'none';
    iconMoon.style.display = isDark ? 'none' : 'flex';
  }

  /** Flip theme, persist it, and update icons. */
  function toggleTheme() {
    const isDark = document.documentElement.classList.toggle('dark');
    document.documentElement.style.colorScheme = isDark ? 'dark' : 'light';
    localStorage.setItem('theme', isDark ? 'dark' : 'light');
    syncThemeIcons();
  }

  syncThemeIcons(); // Run once on load to match the FOUC-prevention script in head.html.

  themeToggleBtn.addEventListener('click', () => {
    document.startViewTransition
      ? document.startViewTransition(toggleTheme)
      : toggleTheme();
  });
})();
